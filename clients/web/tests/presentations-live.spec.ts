import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { AssistantClient } from "@ai-assistant/contracts";

test("creates two slides, restores an old deck and downloads PPTX", async ({ page }) => {
  const origin = process.env.ASSISTANT_WEB_TEST_API_ORIGIN;
  test.skip(!origin || process.env.ASSISTANT_WEB_TEST_SLIDES !== "true", "Requires the isolated presentation API.");
  const username = `qa-slides-web-${randomUUID().slice(0, 8)}`;
  const password = "Qa.Deck-web-fixture!";
  const api = new AssistantClient({ origin: origin! });
  await api.replaceSession(await api.register({ username, password }));
  await api.createProject({ name: "合成幻灯片项目" });
  await page.goto("/");
  await page.getByLabel("用户名").fill(username);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByRole("button", { name: "文稿", exact: true }).click();
  const panel = page.getByRole("dialog", { name: "文稿" });
  await panel.getByLabel("文件格式").selectOption("slides");
  await panel.getByLabel("所属项目").selectOption({ label: "合成幻灯片项目" });
  await panel.getByLabel("文稿标题").fill("合成幻灯片");
  await expect(panel.getByRole("button", { name: "创建幻灯片" })).toBeDisabled();
  await panel.getByLabel("幻灯片标题").fill("第一张报告 🦀");
  await panel.getByRole("button", { name: "新增要点" }).click();
  await panel.getByLabel("要点 1", { exact: true }).fill("只写文字的要点");
  await panel.getByRole("button", { name: "新增幻灯片" }).click();
  await panel.getByLabel("幻灯片标题").fill("第二张报告");
  await panel.getByRole("button", { name: "创建幻灯片" }).click();
  await expect(panel.getByText("已保存版本 1。")).toBeVisible();
  await panel.getByLabel("幻灯片标题").fill("新版本不替代旧版");
  await panel.getByRole("button", { name: "保存新版本" }).click();
  await expect(panel.getByText("已保存版本 2。")).toBeVisible();
  await panel.getByRole("button", { name: "版本 1", exact: true }).click();
  const historical = panel.getByRole("list", { name: "幻灯片内容" });
  await expect(historical).toContainText("第一张报告 🦀");
  await expect(historical).toContainText("第二张报告");
  await panel.getByRole("button", { name: "还原为新版本" }).click();
  await panel.getByRole("button", { name: "确认还原" }).click();
  await expect(panel.getByText("已从版本 1 创建版本 3。")).toBeVisible();
  await expect(panel.getByLabel("幻灯片标题")).toHaveValue("第一张报告 🦀");
  const pending = page.waitForEvent("download");
  await panel.getByRole("button", { name: "下载当前版本" }).click();
  const file = await pending;
  expect(file.suggestedFilename()).toBe("artifact-3.pptx");
  const bytes = await readFile(await file.path());
  expect(bytes.subarray(0, 4)).toEqual(Buffer.from([80, 75, 3, 4]));
  expect(bytes.includes(Buffer.from("ppt/slides/slide2.xml"))).toBe(true);
  await file.delete();
});
